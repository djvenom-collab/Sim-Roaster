// ── Runs across the full planning year (Jan 1 – Dec 31, current year) ────
// Every working day (Mon–Fri, weekends excluded) is seeded with exercises
// for BOTH programs — Radar (RADAR) and Tower (TOWER) — so each sim has
// activity throughout the year. Statuses are derived relative to "today":
// past days are completed/cancelled, today is confirmed/tentative, future
// days rotate through the planning statuses.
const futureStatuses: Run["status"][] = ["confirmed", "tentative", "tentative", "confirmed", "postponed"]
// Separate exercise pools per program so every working day schedules both.
const radarExercises = exercises.filter((e) => e.program === "RADAR")
const towerExercises = exercises.filter((e) => e.program === "TOWER")
const programPools: { pool: Exercise[]; cursor: number }[] = [
  { pool: radarExercises, cursor: 0 },
  { pool: towerExercises, cursor: 0 },
]
export const runs: Run[] = []
let runSeq = 1
{
  const runRng = makeRng(0x5eed12) // deterministic fill of quiet-season days
  // Per-year program balance: RADAR carries the full day's volume, while TOWER
  // schedules a year-varying fraction of it. This makes the two simulators'
  // utilization diverge (and their trend lines cross year to year) instead of
  // sitting on top of each other. CHANGEABLE: the 0.5–0.9 band controls how far
  // TOWER trails RADAR each year.
  const towerYearWeight: Record<number, number> = {}
  {
    const wRng = makeRng(0x704e1207)
    for (let y = HISTORY_START_YEAR; y <= CURRENT_YEAR; y++) towerYearWeight[y] = 0.5 + wRng() * 0.4
  }
  for (let date = HISTORY_START; date <= HISTORY_END; date = addDaysISO(date, 1)) {
    const dow = parseISO(date).getDay() // 0 = Sun … 6 = Sat
    // Working days only: Monday (1) through Friday (5).
    if (dow === 0 || dow === 6) continue
    const offset = daysBetween(T, date) // <0 past, 0 today, >0 future
    // Seasonal volume (identical every year, so past years match the current
    // year): busy campaigns run 2 concurrent sessions per program, shoulder
    // periods run 1, and deep-lean spells are mostly quiet. This gives each
    // year the requested 2–3 major spikes with clear lean troughs between.
    const intensity = seasonalIntensity(date)
    let runsToday: number
    if (intensity > 0.55) runsToday = 2
    else if (intensity > 0.22) runsToday = 1
    else runsToday = runRng() < 0.3 ? 1 : 0 // quiet season → mostly no runs
    if (runsToday === 0) continue
    let slotIndex = 0
    for (let pgIdx = 0; pgIdx < programPools.length; pgIdx++) {
      const pg = programPools[pgIdx]
      if (pg.pool.length === 0) continue
      // RADAR (index 0) runs the full day's volume; TOWER (index 1) runs a
      // year-varying fraction so the two sims accrue clearly different hours.
      let progRuns = runsToday
      if (pgIdx === 1) {
        const w = towerYearWeight[parseISO(date).getFullYear()] ?? 0.7
        let kept = 0
        for (let r = 0; r < runsToday; r++) if (runRng() < w) kept++
        progRuns = kept
      }
      for (let r = 0; r < progRuns; r++) {
        const ex = pg.pool[pg.cursor % pg.pool.length]
        pg.cursor++
        let status: Run["status"]
        if (offset < 0) status = runSeq % 7 === 0 ? "cancelled" : "completed"
        else if (offset === 0) status = r === 0 ? "confirmed" : "tentative"
        else status = futureStatuses[(runSeq + r) % futureStatuses.length]
        runs.push({
          id: datedId("run", date, runSeq),
          date,
          slotTime: slotList[slotIndex % slotList.length],
          simulatorId: ex.simulatorId,
          exerciseId: ex.id,
          status,
          requiredPositions: ex.requiredPositions,
          requiredStaff: ex.requiredStaff,
          notes: runSeq % 8 === 0 ? "Includes trainee under assessment." : undefined,
          cancellationReason: status === "cancelled" ? "Simulator hardware fault" : undefined,
          statusChangedBy:
            status === "confirmed" || status === "cancelled" ? `${staff[7].firstName} ${staff[7].lastName}` : undefined,
          statusChangedAt: status === "confirmed" || status === "cancelled" ? `${date} 09:30` : undefined,
        })
        runSeq++
        slotIndex++
      }
    }
  }
}

// ── Run assignments (scheduled through the SAME rules the app enforces) ───
// For every required seat the scheduler picks the best eligible staff member,
// mirroring the store's Fill Positions logic exactly:
//   • active, belongs to the run's program, has the position as a home position
//   • not already seated elsewhere in the same run (one position per run)
//   • not seated in another run in the same date+slot (no double-booking)
//   • not on leave (any non-rejected leave) that day
//   • not in training that day (as trainee OR instructor)
//   • not committed to another task that day
//   • currency on the position is not expired/never (enforced for today &
//     future runs; relaxed for past runs so history stays fully staffed)
//   • passes the position's qualification rule (no excluded, has all required)
// Priority: expiring currency first (to refresh before lapse), then soonest
// expiry, with a preferred-qual nudge and a fair-workload tiebreak. Some seats
// on non-completed runs are intentionally left open to show incomplete plans.
export const runAssignments: RunAssignment[] = []
{
  // Lookup maps mirroring the store's selectors.
  const validitySeedMap = new Map<string, { lastDateSat: string | null; validityDays: number }>()
  staffValidity.forEach((v) => validitySeedMap.set(`${v.staffId}:${v.positionId}`, { lastDateSat: v.lastDateSat, validityDays: v.validityDays }))

  const qualsByStaff = new Map<string, string[]>()
  staffQualifications.forEach((sq) => {
    const arr = qualsByStaff.get(sq.staffId) ?? []
    arr.push(sq.qualificationId)
    qualsByStaff.set(sq.staffId, arr)
  })

  // training busy: `${staffId}|${date}` for both trainees and instructors.
  const busyTraining = new Set<string>()
  trainingSessions.forEach((t) => busyTraining.add(`${t.instructorId}|${t.date}`))
  trainingAttendance.forEach((a) => {
    const sess = trainingSessions.find((t) => t.id === a.sessionId)
    if (sess) busyTraining.add(`${a.staffId}|${sess.date}`)
  })

  const onLeaveSeed = (staffId: string, date: string) =>
    leaveRecords.some(
      (l) => l.staffId === staffId && l.approval !== "rejected" && date >= l.startDate && date <= l.endDate,
    )
  const onTaskSeed = (staffId: string, date: string) =>
    otherTasks.some((t) => t.staffIds.includes(staffId) && date >= t.startDate && date <= t.endDate)
  // Currency is measured as-of the run's OWN date (not today) so the historical
  // scheduler behaves like it would have on the day: once a person sits a
  // position their currency resets, so they stop being the top pick and seats
  // rotate around the eligible pool instead of clustering on one person.
  const validityStatusSeed = (staffId: string, posId: string, ref: string) => {
    const v = validitySeedMap.get(`${staffId}:${posId}`)
    if (!v) return { status: "never" as const, daysRemaining: null as number | null }
    const c = computeValidity(v.lastDateSat, v.validityDays, ref)
    return { status: c.status, daysRemaining: c.daysRemaining }
  }

  let asgSeq = 1
  let overrideCount = 0
  const MAX_OVERRIDES = 3 // CHANGEABLE: how many TL-approved manual overrides to seed
  const slotBusy = new Map<string, Set<string>>() // date|slot -> staffIds seated
  const workload = new Map<string, number>() // fairness across the whole year
  const posLoad = new Map<string, number>() // `${staffId}|${posId}` -> times sat that exact position (drives rotation)

  for (const run of runs) {
    const ex = exercises.find((e) => e.id === run.exerciseId)
    const program = ex?.program ?? "RADAR"
    const isPast = daysBetween(T, run.date) < 0
    const slotKey = `${run.date}|${run.slotTime}`
    if (!slotBusy.has(slotKey)) slotBusy.set(slotKey, new Set())
    const busySlot = slotBusy.get(slotKey)!
    const assignedThisRun = new Set<string>()

    run.requiredPositions.forEach((posId, pi) => {
      // CHANGEABLE: leave roughly 1 in 5 seats open on non-completed runs to
      // simulate incomplete plans. The "% 5 === 4" is the 1-in-5; raise the 5
      // to fill more seats, or remove this to fill every eligible seat.
      const leaveOpen = run.status !== "completed" && (asgSeq + pi) % 5 === 4
      const rule = positionQualRules.find((r) => r.positionId === posId)
      let chosenId: string | null = null
      let override = false
      let overrideReason: string | undefined

      if (!leaveOpen) {
        const cands: { id: string; score: number; load: number }[] = []
        for (const s of staff) {
          if (!s.active) continue
          if (!s.programs.includes(program)) continue
          if (!s.homePositions.includes(posId)) continue
          if (assignedThisRun.has(s.id)) continue
          if (busySlot.has(s.id)) continue
          if (onLeaveSeed(s.id, run.date)) continue
          if (busyTraining.has(`${s.id}|${run.date}`)) continue
          if (onTaskSeed(s.id, run.date)) continue
          const sq = qualsByStaff.get(s.id) ?? []
          if (rule) {
            if (rule.excludedQuals.some((q) => sq.includes(q))) continue
            if (rule.requiredQuals.some((q) => !sq.includes(q))) continue
          }
          // Past runs: judge currency as-of the run day (drives rotation).
          // Today/future runs: judge as-of today, matching the live app's gate.
          const v = validityStatusSeed(s.id, posId, isPast ? run.date : T)
          if (!isPast && (v.status === "expired" || v.status === "never")) continue
          let score = v.daysRemaining ?? 999
          if (v.status === "expiring") score -= 1000 // expiring outranks merely-valid
          if (rule?.preferredQuals.some((q) => sq.includes(q))) score -= 5
          // Rotation: the more times this person has already sat THIS position,
          // the lower they rank for it, so seats rotate around the eligible pool
          // instead of one person owning a position all year.
          score += (posLoad.get(`${s.id}|${posId}`) ?? 0) * 30
          cands.push({ id: s.id, score, load: workload.get(s.id) ?? 0 })
        }
        cands.sort((a, b) => a.score - b.score || a.load - b.load || (a.id < b.id ? -1 : 1))
        const pick = cands[0]
        if (pick) {
          chosenId = pick.id
          // Sprinkle a few TL-approved overrides on future seats to keep the
          // manual-override feature populated (still an eligible candidate).
          if (!isPast && overrideCount < MAX_OVERRIDES && asgSeq % 53 === 0) {
            override = true
            overrideReason = "Operational necessity – TL approved"
            overrideCount++
          }
        }
      }

      if (chosenId) {
        assignedThisRun.add(chosenId)
        busySlot.add(chosenId)
        workload.set(chosenId, (workload.get(chosenId) ?? 0) + 1)
        posLoad.set(`${chosenId}|${posId}`, (posLoad.get(`${chosenId}|${posId}`) ?? 0) + 1)
        // A COMPLETED run is a real, delivered session, so it refreshes the
        // person's currency on that position. Runs are seeded in chronological
        // order, so the LAST completed run per staff+position ends up as their
        // true "last date sat" — making the profile Validity tab and Run History
        // always agree. Cancelled/postponed runs never happened, so they never
        // refresh currency.
        if (run.status === "completed") {
          const key = `${chosenId}:${posId}`
          const cur = validitySeedMap.get(key)
          if (cur) validitySeedMap.set(key, { ...cur, lastDateSat: run.date })
        }
      }
      runAssignments.push({
        id: datedId("asg", run.date, asgSeq++),
        runId: run.id,
        positionId: posId,
        staffId: chosenId,
        manualOverride: override || undefined,
        overrideReason,
      })
    })
  }

  // Sync the derived "last date sat" back into the exported validity records so
  // every profile's Validity tab shows the EXACT date of the person's most
  // recent completed run on that position — matching their Run History — rather
  // than an unrelated random date. Positions never sat in a completed run keep
  // their seeded baseline (so currency still varies: valid / expiring / expired).
  for (const v of staffValidity) {
    const derived = validitySeedMap.get(`${v.staffId}:${v.positionId}`)
    if (derived) v.lastDateSat = derived.lastDateSat
  }
}

// ── Currency-warning caps (authoritative) ────────────────────────────────
// The completed-run sync above can leave a position reading as expiring or
// expired whenever it was last sat before a quiet spell — which, across the
// whole roster, adds up to a noisy dashboard. For a clean demo we keep only a
// small, fixed number of expiring + expired records team-wide and refresh
// everything else to comfortably valid. Deterministic (stable sort), so the
// exact same records are shown every reload. Valid/never records are untouched,
// so the vast majority of profiles still show their real last-sat date.
{
  const TARGET_EXPIRED = 2 // CHANGEABLE: expired-currency records team-wide (kept minimal)
  const TARGET_EXPIRING = 3 // CHANGEABLE: expiring-soon records team-wide (kept minimal)
  let keepExpired = TARGET_EXPIRED
  let keepExpiring = TARGET_EXPIRING
  const ordered = [...staffValidity].sort((a, b) =>
    `${a.staffId}:${a.positionId}` < `${b.staffId}:${b.positionId}` ? -1 : 1,
  )
  for (const v of ordered) {
    const status = computeValidity(v.lastDateSat, v.validityDays).status
    if (status === "expired" && keepExpired > 0) {
      keepExpired--
      continue
    }
    if (status === "expiring" && keepExpiring > 0) {
      keepExpiring--
      continue
    }
    if (status === "expired" || status === "expiring") {
      // Over the team-wide budget → refresh to comfortably valid (well outside
      // the 14-day warning window).
      v.lastDateSat = addDaysISO(T, -Math.max(1, Math.floor(v.validityDays / 4)))
    }
  }
}

// ── Currency top-up (authoritative for the LIVE app) ─────────────────────
// The store derives every person's currency from their COMPLETED run history
// (see validityMap in lib/store.tsx), NOT from the seeded staffValidity dates
// above — so with the quarterly volume curve some held positions naturally drift
// into expiring/expired by "today" (e.g. when the current year's low quarter
// falls early). To keep conflicts and currency alerts at the requested minimum,
// we seed a recent "revalidation" completed run for each lapsing held position,
// leaving only a small handful of alerts for realism. Deterministic (stable
// sort), so the same records show every reload.
{
  const KEEP_EXPIRED = 2 // CHANGEABLE: expired alerts left on the live dashboard
  const KEEP_EXPIRING = 3 // CHANGEABLE: expiring alerts left on the live dashboard
  const staffByIdMap = new Map(staff.map((s) => [s.id, s]))
  const posByIdMap = new Map(positions.map((p) => [p.id, p]))
  const runByIdMap = new Map(runs.map((r) => [r.id, r]))
  // Most-recent completed run per staff:position — mirrors the store exactly.
  const lastSat = new Map<string, string>()
  for (const a of runAssignments) {
    if (!a.staffId) continue
    const r = runByIdMap.get(a.runId)
    if (!r || r.status !== "completed" || r.date > T) continue
    const k = `${a.staffId}:${a.positionId}`
    const prev = lastSat.get(k)
    if (!prev || r.date > prev) lastSat.set(k, r.date)
  }
  // Deterministically ordered list of lapsing HELD combos (active staff only).
  const lapsing: { staffId: string; posId: string; status: "expired" | "expiring" }[] = []
  for (const [k, date] of [...lastSat.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1))) {
    const [staffId, posId] = k.split(":")
    const s = staffByIdMap.get(staffId)
    if (!s || !s.active || !s.homePositions.includes(posId)) continue
    const p = posByIdMap.get(posId)
    if (!p) continue
    const st = computeValidity(date, p.validityDays, T).status
    if (st === "expired" || st === "expiring") lapsing.push({ staffId, posId, status: st })
  }
  // Refresh all but a small kept remainder by appending a completed revalidation
  // run dated a few days ago (well inside every validity window → reads valid).
  let keepE = KEEP_EXPIRED
  let keepG = KEEP_EXPIRING
  let topupSeq = 1
  for (const { staffId, posId, status } of lapsing) {
    if (status === "expired" && keepE > 0) {
      keepE--
      continue
    }
    if (status === "expiring" && keepG > 0) {
      keepG--
      continue
    }
    const s = staffByIdMap.get(staffId)!
    const program = s.programs[0] ?? "RADAR"
    const ex =
      exercises.find((e) => e.program === program && e.requiredPositions.includes(posId)) ??
      exercises.find((e) => e.program === program) ??
      exercises[0]
    const date = addDaysISO(T, -(5 + (topupSeq % 10))) // 5–14 days ago, spread out
    const runId = datedId("run", date, 900000 + topupSeq)
    runs.push({
      id: runId,
      date,
      slotTime: slotList[topupSeq % slotList.length],
      simulatorId: ex.simulatorId,
      exerciseId: ex.id,
      status: "completed",
      requiredPositions: [posId],
      requiredStaff: 1,
      notes: "Currency revalidation session.",
    })
    runAssignments.push({
      id: datedId("asg", date, 900000 + topupSeq),
      runId,
      positionId: posId,
      staffId,
    })
    // Keep the raw staffValidity export consistent with the run-derived view.
    const rec = staffValidity.find((v) => v.staffId === staffId && v.positionId === posId)
    if (rec) rec.lastDateSat = date
    topupSeq++
  }
}

