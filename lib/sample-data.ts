// ── OJTI training log (daily on-the-job records per trainee) ──────────────
// Instructors (OJTI-qualified staff) log a trainee's daily OJT: the position
// group worked, hours trained, a performance rating and written feedback.
// Seeded across recent weekdays so the log opens with realistic history.
export const trainingLogs: TrainingLogEntry[] = []
{
  const OJTI_QUAL = "q-ojti"
  const GROUP_CAP = 40 // hours of OJT per group before validation (extension possible)
  const strengthsPool = [
    "Strong traffic picture and confident phraseology throughout.",
    "Good separation planning and early conflict detection.",
    "Clear, concise R/T and well-structured coordination.",
    "Maintained situational awareness under increasing complexity.",
    "Prioritised effectively and used silent periods to plan ahead.",
  ]
  const improvePool = [
    "Tighten sequencing on the final; a couple of gaps were larger than needed.",
    "Coordinate handoffs slightly earlier during peak inbound flows.",
    "Watch readback discipline when workload spikes.",
    "Build a more proactive plan for departures against the arrival stream.",
    "Verbalise the plan sooner so intentions are clear to the coordinator.",
  ]
  const remarkPool = [
    "Good session overall — steady, measurable progress.",
    "Solid consolidation day. Ready to progress complexity next block.",
    "Debriefed scenarios in full; trainee receptive to feedback.",
    "Recommend one more session at this level before assessment.",
    "Confidence building well; keep reinforcing the basics.",
  ]

  // Small deterministic string hash → seed, so each (trainee, group) session
  // stream is stable across reloads yet independent of the others.
  const hashSeed = (s: string) => {
    let h = 0x811c9dc5
    for (let i = 0; i < s.length; i++) {
      h ^= s.charCodeAt(i)
      h = Math.imul(h, 0x01000193)
    }
    return h >>> 0
  }

  // ── Designate an OJTI bench per program ──────────────────────────────────
  // Keep any hand-authored OJTIs (staff-1, staff-3 …) and top each program up
  // to at least three instructors so both RADAR and TOWER have a trainer bench.
  const seededOjti = new Set(
    staffQualifications.filter((q) => q.qualificationId === OJTI_QUAL).map((q) => q.staffId),
  )
  const ojtiByProgram: Record<"RADAR" | "TOWER", Staff[]> = { RADAR: [], TOWER: [] }
  for (const program of ["TOWER", "RADAR"] as const) {
    const inProgram = staff.filter((s) => s.programs.includes(program))
    const chosen: Staff[] = inProgram.filter((s) => seededOjti.has(s.id))
    for (let k = 0; k < inProgram.length && chosen.length < 3; k++) {
      if (!chosen.some((c) => c.id === inProgram[k].id)) chosen.push(inProgram[k])
    }
    ojtiByProgram[program] = chosen
  }
  const ojtiStaffIds = new Set([...ojtiByProgram.RADAR, ...ojtiByProgram.TOWER].map((s) => s.id))

  // Requirement: anyone who instructs must hold the OJTI qualification. Backfill
  // it for every designated OJTI that wasn't already hand-authored above.
  for (const id of ojtiStaffIds) {
    if (!seededOjti.has(id)) {
      staffQualifications.push({ id: `sq-ojti-${id}`, staffId: id, qualificationId: OJTI_QUAL })
    }
  }

  // ── Complete trainee coverage ────────────────────────────────────────────
  // Every non-OJTI staff member is a trainee and must show accumulated hours on
  // EVERY position group of their program. ~1 in 4 groups is fully validated
  // (≥40h, occasionally an approved extension); the rest are still in progress,
  // so the staff page and the OJTI tab both show a realistic mix.
  let logSeq = 1
  const trainees = staff.filter((s) => !ojtiStaffIds.has(s.id))
  for (const trainee of trainees) {
    const program = trainee.programs[0] as "RADAR" | "TOWER"
    const ojtis = ojtiByProgram[program]
    if (ojtis.length === 0) continue
    const groups = TRAINING_GROUPS.filter((g) => g.program === program)
    for (let gi = 0; gi < groups.length; gi++) {
      const group = groups[gi]
      const rng = makeRng(hashSeed(`${trainee.id}:${group.id}`))
      const completed = rng() < 0.25
      const target = completed
        ? GROUP_CAP + Math.round(rng() * 12) // 40–52h (may include an approved extension)
        : Math.round((4 + rng() * 32) * 2) / 2 // 4–36h in 0.5h steps (in progress)
      let remaining = target
      let dayCursor = 20 + gi * 9 + Math.floor(rng() * 15) // stagger groups over time
      let ojtiRot = Math.floor(rng() * ojtis.length)
      let guard = 0
      while (remaining > 0.01 && guard++ < 60) {
        // Advance to the next weekday.
        let date = addDaysISO(T, -dayCursor)
        let dow = parseISO(date).getDay()
        while (dow === 0 || dow === 6) {
          dayCursor++
          date = addDaysISO(T, -dayCursor)
          dow = parseISO(date).getDay()
        }
        const chunk = Math.min(remaining, Math.round((2 + rng() * 3) * 2) / 2) // 2–5h
        const ojti = ojtis[ojtiRot % ojtis.length]
        ojtiRot++
        // Train 1–2 of the group's positions.
        const shuffled = [...group.positionIds].sort(() => rng() - 0.5)
        const positionIds = shuffled.slice(0, 1 + Math.floor(rng() * Math.min(2, shuffled.length)))
        const rating = 2 + Math.floor(rng() * 4) // 2–5
        trainingLogs.push({
          id: datedId("tlog", date, logSeq++),
          date,
          program,
          groupId: group.id,
          positionIds,
          ojtiId: ojti.id,
          traineeId: trainee.id,
          hours: chunk,
          rating,
          strengths: strengthsPool[Math.floor(rng() * strengthsPool.length)],
          areasToImprove: improvePool[Math.floor(rng() * improvePool.length)],
          feedback: remarkPool[Math.floor(rng() * remarkPool.length)],
          createdAt: `${date}T17:00:00.000Z`,
        })
        remaining -= chunk
        dayCursor += 3 + Math.floor(rng() * 6) // 3–8 days between sessions
      }
    }
  }
}

