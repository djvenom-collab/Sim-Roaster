// ── Validity per staff/position ──────────────────��──────────────────────
// Rules enforced here:
//  • Everyone is VALID on at least their first 3 home positions.
//  • Only a small, capped number of EXPIRED records exist across the whole
//    roster, each on a different person.
//  • A small number of records are EXPIRING soon (≤14 days remaining).
//  • Remaining extra positions stay valid.
// NOTE: a completed run refreshes currency, so the numbers here are only a
// starting point — the authoritative team-wide caps are enforced by the
// normalization pass AFTER run assignments are seeded (see further below).
const MAX_EXPIRED = 2 // CHANGEABLE: how many "expired currency" records to seed across everyone
let expiredBudget = MAX_EXPIRED
export const staffValidity: StaffValidity[] = []
staff.forEach((s, si) => {
  s.homePositions.forEach((posId, k) => {
    const p = positions.find((pp) => pp.id === posId)
    if (!p) return
    const vd = p.validityDays
    let lastDateSat: string | null
    if (k < 3) {
      // Guaranteed valid: sat recently, leaving plenty of currency remaining.
      const ago = (si * 3 + k * 7) % Math.max(5, Math.floor(vd / 3))
      lastDateSat = addDaysISO(T, -ago) // daysRemaining = vd - ago (well above 14)
    } else {
      // Extra positions: seed a tiny, capped number of expired records and
      // leave everyone else comfortably valid. (Completed-run refresh below
      // reshapes this, and the normalization pass enforces the final caps.)
      const r = (si + k) % 7
      if (r === 0 && expiredBudget > 0) {
        expiredBudget--
        lastDateSat = addDaysISO(T, -(vd + 5 + (si % 10))) // past expiry → expired
      } else {
        lastDateSat = addDaysISO(T, -((si + k) % Math.max(5, Math.floor(vd / 3)))) // valid
      }
    }
    staffValidity.push({
      staffId: s.id,
      positionId: p.id,
      lastDateSat,
      validityDays: vd,
    })
  })
})

// ── Leave (full calendar span, including FUTURE planned leave) ───────────
// Every retained year — including the CURRENT year — gets a full Jan–Dec span,
// so the app carries realistic upcoming/planned leave through 31 Dec of the
// current year (surfaced by the dashboard "Upcoming Leave" panel and the leave
// calendar). Historical leave stays "approved"-heavy; future leave is a
// believable mix of approved + pending requests. Leave is generated BEFORE run
// assignments and the scheduler skips anyone on non-rejected leave, so future
// leave never collides with a seated run.
const leaveTypes: LeaveRecord["type"][] = ["Annual", "Sick", "Course", "Training", "Compassionate"]
export const leaveRecords: LeaveRecord[] = []
{
  const rng = makeRng(0x1eaf2026)
  let lvSeq = 1
  // One pass per seeded year, every year spanning the full Jan–Dec calendar so
  // both history AND forward planning are populated.
  for (let year = HISTORY_START_YEAR; year <= CURRENT_YEAR; year++) {
    const yearStart = `${year}-01-01`
    const yearEnd = `${year}-12-31`
    const span = daysBetween(yearStart, yearEnd) // days available this year
    if (span < 1) continue
    staff.forEach((s) => {
      const spells = 1 + Math.floor(rng() * 3) // CHANGEABLE: 1–3 leave spells per person / year
      for (let k = 0; k < spells; k++) {
        // Mild bias toward LEAN periods: sample TWO candidate start days and keep
        // the quieter one. This is only a gentle nudge (best of 2), so leave
        // still spreads across the WHOLE year — including the second half — which
        // keeps forward-looking "upcoming leave" populated instead of clustering
        // everything into the single leanest stretch (a stronger bias did).
        let startDate = addDaysISO(yearStart, Math.floor(rng() * span))
        const cand = addDaysISO(yearStart, Math.floor(rng() * span))
        if (seasonalIntensity(cand) < seasonalIntensity(startDate)) {
          startDate = cand
        }
        let endDate = addDaysISO(startDate, Math.floor(rng() * 5)) // 0–4 extra days
        if (endDate > yearEnd) endDate = yearEnd // clamp within the year
        const fullDay = rng() > 0.2
        const approval: LeaveRecord["approval"] = rng() > 0.15 ? "approved" : rng() > 0.5 ? "pending" : "rejected"
        leaveRecords.push({
          id: datedId("lv", startDate, lvSeq++),
          staffId: s.id,
          type: leaveTypes[Math.floor(rng() * leaveTypes.length)],
          startDate,
          endDate,
          fullDay,
          approval,
          notes: !fullDay ? "Half day" : undefined,
        })
      }
    })
  }
}

