// Small deterministic PRNG (mulberry32) so the random sample data is stable
// across reloads while still looking organically spread out.
function makeRng(seed: number) {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) | 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

// ── Seasonal demand curve (quarterly) ────────────────────────────────────
// Activity changes QUARTER by QUARTER, not week by week. Each calendar year is
// assigned one busy (high) quarter, one quiet (low) quarter, and two medium
// quarters — but WHICH quarter is which is randomized per year, and each year
// also gets an overall factor so some years run slow and some run intense. The
// result is a smooth seasonal wave with a single yearly peak and trough that
// still varies believably from year to year. Deterministic (seeded by year),
// so server and client agree and reloads are stable.
const QUARTER_LEVEL = { high: 0.85, med: 0.45, low: 0.16 }

interface YearProfile {
  levels: [number, number, number, number] // intensity at each quarter's centre
}
const yearProfileCache = new Map<number, YearProfile>()
function yearProfile(year: number): YearProfile {
  const cached = yearProfileCache.get(year)
  if (cached) return cached
  // Distinct deterministic RNG per year.
  const rng = makeRng((0x9e3779b1 ^ Math.imul(year, 2654435761)) >>> 0)
  // Pick the high and (distinct) low quarter; the rest are medium.
  const highQ = Math.floor(rng() * 4) % 4
  let lowQ = Math.floor(rng() * 4) % 4
  while (lowQ === highQ) lowQ = Math.floor(rng() * 4) % 4
  // Overall year factor: ~0.8 (slow year) … ~1.15 (intense year).
  const factor = 0.8 + rng() * 0.35
  const levels = [0, 1, 2, 3].map((q) => {
    const base = q === highQ ? QUARTER_LEVEL.high : q === lowQ ? QUARTER_LEVEL.low : QUARTER_LEVEL.med
    return Math.min(1, base * factor)
  }) as [number, number, number, number]
  const profile: YearProfile = { levels }
  yearProfileCache.set(year, profile)
  return profile
}

function smoothstep(t: number): number {
  const x = Math.max(0, Math.min(1, t))
  return x * x * (3 - 2 * x)
}

// Returns 0 (deep lean) … 1 (peak) for a given date, interpolating smoothly
// between the four quarter-centre levels so the wave has one clear peak/trough.
function seasonalIntensity(iso: string): number {
  const y = Number(iso.slice(0, 4))
  const { levels } = yearProfile(y)
  const dayOfYear = daysBetween(`${y}-01-01`, iso)
  const yearLen = daysBetween(`${y}-01-01`, `${y + 1}-01-01`)
  const frac = yearLen > 0 ? Math.min(0.999, dayOfYear / yearLen) : 0
  const centers = [0.125, 0.375, 0.625, 0.875]
  if (frac <= centers[0]) return levels[0]
  if (frac >= centers[3]) return levels[3]
  for (let i = 0; i < 3; i++) {
    if (frac >= centers[i] && frac < centers[i + 1]) {
      const t = smoothstep((frac - centers[i]) / (centers[i + 1] - centers[i]))
      return levels[i] + (levels[i + 1] - levels[i]) * t
    }
  }
  return levels[3]
}

// ── Courses ────────────────────────────────────────────────────────────────
// A Course groups several exercises into a multi-week delivery that needs a
// fixed headcount for its whole duration. Built from the seeded exercises with
// a FIXED rng so the demo set is the same every reload (and matches between
// server and client), while still looking random with intentional overlaps.
// These are fully editable at runtime via the store (and persisted locally).
// SIM-bucket assignment for every generated course (SIM Operational vs SIM
// Non-Operational). Populated inside the courses IIFE below and exported so the
// exercise sheet's tree is fully filled out from a fresh seed. Alternated within
// each course group so both buckets stay populated under both branches.
const courseSimClassSeed: Record<string, "operational" | "non-operational"> = {}

export const courses: Course[] = (() => {
  const rng = makeRng(73108)
  const pick = <X,>(arr: X[]): X => arr[Math.floor(rng() * arr.length)]
  const pickSome = <X,>(arr: X[], n: number): X[] => {
    const copy = [...arr]
    const out: X[] = []
    for (let i = 0; i < n && copy.length > 0; i++) {
      out.push(copy.splice(Math.floor(rng() * copy.length), 1)[0])
    }
    return out
  }
  const names = ["Alpha", "Bravo", "Charlie", "Delta", "Echo", "Foxtrot", "Golf", "Hotel", "India", "Juliet", "Kilo", "Lima"]
  const trainingThemes = ["Refresher", "Conversion", "Recurrent", "Unit Familiarisation", "Emergency Procedures", "LVP Training"]
  const validationThemes = ["Competency Check", "Annual Revalidation", "Rating Renewal", "Unit Endorsement", "Assessment Board", "Skill Validation"]
  const out: Course[] = []
  let seq = 1
  let nameIdx = 0

  // Alternate bucket assignment so SIM Operational and SIM Non-Operational each
  // receive courses within every group (keeps all four tree cells populated).
  const assignBucket = (courseId: string, i: number) => {
    courseSimClassSeed[courseId] = i % 2 === 0 ? "operational" : "non-operational"
  }

  // Generate the same course structure for EVERY retained year (history +
  // current) so the Yearly Gantt is populated under past years too, not just the
  // current year. Dates are re-anchored to each year and ids are year-infixed for
  // uniqueness; the shared rng stream keeps it deterministic yet varied per year.
  for (let year = HISTORY_START_YEAR; year <= CURRENT_YEAR; year++) {
    const yearStart = `${year}-01-01`
    for (const program of ["RADAR", "TOWER"] as const) {
      const pool = exercises.filter((e) => e.program === program)
      if (pool.length === 0) continue
      // Validation is kept SEPARATE from normal: normal + training courses draw
      // only from non-validation exercises, and validation courses draw only from
      // validation exercises, so each course sits under exactly one tree branch.
      const normalPool = pool.filter((e) => !e.isValidation)
      const validationPool = pool.filter((e) => e.isValidation)
      const normSrc = normalPool.length ? normalPool : pool
      const valSrc = validationPool.length ? validationPool : pool
      const prefix = program === "RADAR" ? "RAD" : "TWR"

      // CHANGEABLE: 10 multi-week exercise courses per program (NORMAL exercises),
      // staggered across the whole year with jitter + overlaps so it looks organic.
      const exCourses = 10
      for (let i = 0; i < exCourses; i++) {
        const slot = Math.floor((i / exCourses) * 48) // even spread Wk 1–48
        const startWeek = Math.min(50, 1 + slot + Math.floor(rng() * 5)) // + jitter
        const lengthWeeks = 4 + Math.floor(rng() * 7) // 4–10 weeks
        const startDate = addDaysISO(yearStart, (startWeek - 1) * 7)
        const endDate = addDaysISO(startDate, lengthWeeks * 7 - 1)
        const exCount = 2 + Math.floor(rng() * 4) // 2–5 exercises
        const id = `course-${year}-${seq}`
        out.push({
          id,
          code: `${prefix}-C${i + 1}`,
          name: `${program} Course ${names[nameIdx++ % names.length]}`,
          program,
          kind: "exercise",
          exerciseIds: pickSome(normSrc, Math.min(exCount, normSrc.length)).map((e) => e.id),
          startDate,
          endDate,
          requiredPeople: 4 + Math.floor(rng() * 9), // 4–12 people
          active: true,
        })
        assignBucket(id, i)
        seq++
      }

      // CHANGEABLE: 6 shorter training courses per program (NORMAL exercises).
      const trCourses = 6
      for (let i = 0; i < trCourses; i++) {
        const slot = Math.floor(((i + 0.5) / trCourses) * 48) // offset spread
        const startWeek = Math.min(51, 1 + slot + Math.floor(rng() * 4))
        const lengthWeeks = 1 + Math.floor(rng() * 4) // 1–4 weeks
        const startDate = addDaysISO(yearStart, (startWeek - 1) * 7)
        const endDate = addDaysISO(startDate, lengthWeeks * 7 - 1)
        const id = `course-${year}-${seq}`
        out.push({
          id,
          code: `${prefix}-T${i + 1}`,
          name: `${program} ${pick(trainingThemes)}`,
          program,
          kind: "training",
          exerciseIds: pickSome(normSrc, Math.min(1 + Math.floor(rng() * 2), normSrc.length)).map((e) => e.id),
          startDate,
          endDate,
          requiredPeople: 3 + Math.floor(rng() * 6), // 3–8 people
          active: true,
        })
        assignBucket(id, i)
        seq++
      }

      // CHANGEABLE: 6 validation courses per program (VALIDATION exercises only),
      // kept as their own group so they populate the tree's Validation branch.
      const vCourses = 6
      for (let i = 0; i < vCourses; i++) {
        const slot = Math.floor(((i + 0.25) / vCourses) * 48) // offset spread
        const startWeek = Math.min(51, 1 + slot + Math.floor(rng() * 4))
        const lengthWeeks = 1 + Math.floor(rng() * 3) // 1–3 weeks
        const startDate = addDaysISO(yearStart, (startWeek - 1) * 7)
        const endDate = addDaysISO(startDate, lengthWeeks * 7 - 1)
        const exCount = 1 + Math.floor(rng() * 3) // 1–3 validation exercises
        const id = `course-${year}-${seq}`
        out.push({
          id,
          code: `${prefix}-V${i + 1}`,
          name: `${program} Validation ${validationThemes[i % validationThemes.length]}`,
          program,
          kind: "exercise",
          exerciseIds: pickSome(valSrc, Math.min(exCount, valSrc.length)).map((e) => e.id),
          startDate,
          endDate,
          requiredPeople: 3 + Math.floor(rng() * 5), // 3–7 people
          active: true,
        })
        assignBucket(id, i)
        seq++
      }
    }
  }
  return out
})()

