// Sessions before today are marked "completed" (with attendance recorded),
// sessions today or later are "scheduled". Each session enrols an instructor
// plus 2–5 trainees drawn from the staff roster.
export const trainingSessions: TrainingSession[] = []
export const trainingAttendance: TrainingAttendance[] = []
{
  const rng = makeRng(0x5ab12026)
  let trSeq = 1
  let taSeq = 1
  for (let date = HISTORY_START; date <= HISTORY_END; date = addDaysISO(date, 1)) {
    // Generate through the end of the current year, INCLUDING future dates, so
    // the app has upcoming/scheduled training (shown on the dashboard "Upcoming
    // Training" panel and the Gantt). Past dates become "completed"; today and
    // later become "scheduled" via the isPast branch below.
    const dow = parseISO(date).getDay()
    if (dow === 0 || dow === 6) continue // working days only (Mon–Fri)
    // Seasonal: training clusters around the busy campaigns too, so the
    // Training trend line peaks in step with runs. The same curve is applied to
    // every year, so past years match the current year's shape and volume.
    const hostChance = 0.05 + 0.32 * seasonalIntensity(date) // ~5% lean … ~37% peak
    if (rng() > hostChance) continue
    const [type, title] = trainingTypeTitles[Math.floor(rng() * trainingTypeTitles.length)]
    const instructorIdx = Math.floor(rng() * staff.length)
    const instructor = staff[instructorIdx]
    const withSim = rng() > 0.4
    const sim = simulators[Math.floor(rng() * simulators.length)]
    const isPast = date < T
    const sessionId = datedId("tr", date, trSeq++)
    trainingSessions.push({
      id: sessionId,
      title,
      type,
      date,
      slotTime: slotList[Math.floor(rng() * slotList.length)],
      instructorId: instructor.id,
      simulatorId: withSim && sim ? sim.id : undefined,
      notes: trSeq % 6 === 0 ? "Mandatory annual." : undefined,
      status: isPast ? "completed" : "scheduled",
    })
    // Enrol 2–5 trainees (never the instructor) for this session.
    const traineeCount = 2 + Math.floor(rng() * 4)
    const used = new Set<number>([instructorIdx])
    for (let k = 0; k < traineeCount; k++) {
      let idx = Math.floor(rng() * staff.length)
      let guard = 0
      while (used.has(idx) && guard < staff.length) {
        idx = (idx + 1) % staff.length
        guard++
      }
      if (used.has(idx)) break
      used.add(idx)
      trainingAttendance.push({
        id: datedId("ta", date, taSeq++),
        sessionId,
        staffId: staff[idx].id,
        // Past sessions: most trainees attended; future sessions: not yet.
        attended: isPast ? rng() > 0.12 : false,
      })
    }
  }
}

