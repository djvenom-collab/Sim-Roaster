// Exercises delivered — [program, simulatorId, course code, required staff].
// Courses ending in " V" are validation deliveries (isValidation = true).
// Sourced from the active DIM dataset.
//
// The raw DIM list repeats the same code across different simulators/headcounts,
// which would produce multiple exercises sharing one name. Every exercise name
// must be unique, so we collapse the list to the FIRST row per (program + code).
const rawCourseList: [string, string, string, number][] = dimCourseList
const seenCourseKeys = new Set<string>()
const courseList: [string, string, string, number][] = rawCourseList.filter((row) => {
  const key = `${row[0]}|${row[2].trim().toUpperCase()}`
  if (seenCourseKeys.has(key)) return false
  seenCourseKeys.add(key)
  return true
})

export const exercises: Exercise[] = courseList.map(([program, simulatorId, code, requiredStaff], i) => {
  const isValidation = / V$/.test(code)
  const baseName = code.replace(/ V$/, "").trim()
  const programPositions = positions.filter((p) => p.program === program)
  // Named seats for this delivery. Rather than always taking the SAME first N
  // positions (which would leave later-sorted positions like AIR / GMC / OSS
  // never scheduled and therefore never "sat"), rotate the window of required
  // positions per exercise. Over the year every position gets delivered, so
  // everyone builds real currency on every position they hold — no orphaned
  // "never sat" seats. Headcount (requiredStaff) still equals the seat count.
  const n = Math.min(requiredStaff, programPositions.length)
  const start = (i * 3) % Math.max(1, programPositions.length)
  const requiredPositions = Array.from(
    { length: n },
    (_, k) => programPositions[(start + k) % programPositions.length].id,
  )
  return {
    id: `ex-${i + 1}`,
    code,
    name: isValidation ? `${baseName} Validation` : baseName,
    program,
    description: isValidation
      ? `Validation delivery of ${baseName}.`
      : `${baseName} course delivery.`,
    durationMin: 120,
    simulatorId,
    requiredStaff: n,
    isValidation,
    requiredPositions,
    active: true,
  }
})

